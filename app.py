LEGACY_DEMO_EMAIL = 'demo@gapfinder.ai'

def authenticated(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        if not active_student():
            return jsonify(error='Please sign in.'), 401
        if DATABASE_URL:
            with db() as connection:
                connection.execute('SELECT id FROM users WHERE id=? FOR UPDATE', (session['user_id'],))
                g.student_connection = connection
                try:
                    return fn(*args, **kwargs)
                finally:
                    g.pop('student_connection', None)
        with locks.setdefault(session['user_id'], threading.RLock()):
            return fn(*args, **kwargs)
    return wrapper

