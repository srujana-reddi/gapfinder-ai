@contextmanager
def db():
    if DATABASE_URL:
        if 'student_connection' in g:
            yield g.student_connection
        else:
            with PostgresConnection.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10) as connection:
                yield connection
        return
    conn = sqlite3.connect(DB, timeout=30)
    conn.row_factory = sqlite3.Row
    try:
        with conn:
            yield conn
    finally:
        conn.close()

database_ready = False
database_init_lock = threading.Lock()

def initialize_db():
    global database_ready
    with database_init_lock:
        if database_ready:
            return
        with db() as c:
            if DATABASE_URL:
                c.execute('SELECT pg_advisory_xact_lock(784212)')
            id_type = 'BIGINT GENERATED BY DEFAULT AS IDENTITY' if DATABASE_URL else 'INTEGER'
            c.execute(f'CREATE TABLE IF NOT EXISTS users (id {id_type} PRIMARY KEY, email TEXT UNIQUE, name TEXT, password TEXT, state TEXT)')
        database_ready = True


@app.before_request
def csrf():
    if request.path.startswith('/api/'):
        initialize_db()
    if 'csrf' not in session:
        session['csrf'] = secrets.token_hex(24)
    if request.path.startswith('/api/') and request.method in ('POST', 'DELETE', 'PUT'):
        if not secrets.compare_digest(request.headers.get('X-CSRF-Token', ''), session['csrf']):
            return jsonify(error='Session expired. Refresh this page and try again.'), 403

