@app.post('/api/quiz')
@authenticated
def make_quiz():
    s, data = state(), body()
    count = int(data.get('count', 6))
    if not 1 <= count <= 12:
        raise ValueError('Choose 1–12 questions.')
    mode = data.get('mode', 'demo')
    if mode not in ('demo', 'ai', 'mcq'):
        raise ValueError('Choose demo or AI mode.')
    selected = data.get('topic_id')
    topics = [t for t in report(s) if not selected or t['id'] == selected]
    topics.sort(key=lambda t: t['score'] if t['score'] is not None else -1)
    viable = [t for t in topics if t['sources']]
    if not viable:
        raise ValueError('Upload a syllabus and matching notes first. Topics without matching notes cannot be assessed.')
    targets = [viable[i % len(viable)] for i in range(count)]
    generated = {}
    if mode != 'demo' and rag.configured():
        style = 'multiple-choice' if mode == 'mcq' else 'short-answer'
        slots = [{'slot': i, 'topic': t['name'], 'sources': [c['id'] for c in t['sources']]}
                 for i, t in enumerate(targets)]
        evidence = {c['id']: {'id': c['id'], 'text': c['text']} for t in targets for c in t['sources']}
        task = (f'Create distinct {style} diagnostic questions for these slots: '
                f'{json.dumps(slots)}. Return a JSON object with a questions array. Each item must '
                'contain slot, prompt, answer, source_id, and a short verbatim quote from one '
                'of that slot’s sources. Omit unsupported slots.')
        if mode == 'mcq':
            task += ' Include four distinct option strings. The answer must equal the correct option exactly.'
        try:
            response = rag.generate(task, list(evidence.values()))
        except ValueError:
            response = {}
        items = response.get('questions', [dict(response, slot=0)] if count == 1 else [])
        for q in items if isinstance(items, list) else []:
            slot = q.get('slot') if isinstance(q, dict) else None
            if type(slot) is not int or not 0 <= slot < count or slot in generated:
                continue
            try:
                source = rag.validate_evidence(q, targets[slot]['sources'])
            except rag.EvidenceError:
                continue
            if not all(isinstance(q.get(k), str) and q[k].strip() for k in ('prompt', 'answer')):
                continue
            question = {k: q[k] for k in ('prompt', 'answer', 'quote', 'source_id')}
            question.update(mode=mode, type=style, source=source)
            if mode == 'mcq':
                options = q.get('options')
                if not isinstance(options, list) or len(options) != 4 or not all(isinstance(o, str) and o.strip() for o in options):
                    continue
                options = [o.strip() for o in options]
                question['answer'] = q['answer'].strip()
                if len({o.casefold() for o in options}) != 4 or question['answer'] not in options:
                    continue
                question['options'] = options
            generated[slot] = question

    questions = []
    used = set()
    for slot, topic in enumerate(targets):
        question = generated.get(slot)
        if not question or question['prompt'] in used:
            question = None
            for offset in range(18):
                sources = topic['sources']
                source = sources[offset % len(sources)]
                candidate = rag.demo_question(topic['name'], source, slot + len(s['attempts']) + offset)
                if not candidate or candidate['prompt'] in used:
                    continue
                candidate.update(source=source, local_fallback=mode != 'demo')
                if mode == 'mcq':
                    answer = candidate['answer']
                    words = re.findall(r'[A-Za-z]{5,}', ' '.join(c['text'] for c in sources))
                    distractors = list(dict.fromkeys(w.lower() for w in words
                                                    if w.casefold() != answer.casefold() and w.lower() not in rag.STOP))
                    distractors.sort(key=lambda w: (abs(len(w) - len(answer)), w))
                    if len(distractors) < 3:
                        continue
                    candidate.update(mode='mcq', type='multiple-choice',
                                     options=[answer, *distractors[:3]])
                question = candidate
                break
        if not question:
            continue
        if question['mode'] == 'mcq':
            secrets.SystemRandom().shuffle(question['options'])
        used.add(question['prompt'])
        question.update(id=uid(), topic_id=topic['id'], topic=topic['name'])
        questions.append(question)
    if not questions:
        raise ValueError('Not enough readable material for this topic. Try another topic or upload more notes.')
    quiz = {'id': uid(), 'date': now(), 'questions': questions, 'submitted': False}
    s['quizzes'].append(quiz)
    save(s)
    return jsonify(public_quiz(quiz))

