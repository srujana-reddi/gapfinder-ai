def rebuild_topic_map(s):
    previous = {t['name'].casefold(): t for t in s['topics']}
    topics = [t for t in s['topics'] if not t.get('document_id')]
    seen = {t['name'].casefold() for t in topics}
    for doc in s['documents']:
        if doc['kind'] != 'syllabus':
            continue
        chunks = [c['text'] for c in s['chunks'] if c['document_id'] == doc['id']]
        for title in broad_topics('\n'.join(chunks)):
            key = title.casefold()
            if key not in seen:
                topics.append({'id': previous[key]['id'] if key in previous else uid(),
                               'name': title, 'parent': '', 'document_id': doc['id']})
                seen.add(key)
    s['topics'] = topics

def report(s):
    result = []
    mapped = mappings(s)
    for topic in s['topics']:
        history = []
        for attempt in s['attempts']:
            answers = [a for a in attempt['results'] if a['topic_id'] == topic['id']]
            if answers:
                history.append({'date': attempt['date'], 'score': round(100 * sum(a['score'] for a in answers) / len(answers)), 'count': len(answers)})
        score = history[-1]['score'] if history else None
        level = 'untested' if score is None else 'weak' if score < 50 else 'medium' if score < 80 else 'strong'
        reasons = [r['feedback'] for a in reversed(s['attempts']) for r in a['results'] if r['topic_id'] == topic['id'] and r['score'] < 1][:2]
        coverage = rag.retrieve(topic['name'], [c for c in s['chunks'] if c['kind'] == 'notes'], 3)
        frequency = sum(m['topic_id'] == topic['id'] for m in mapped)
        result.append(dict(topic, score=score, level=level, history=history, exam_frequency=frequency,
                           sources=coverage, reason='Not assessed yet; take a diagnostic before drawing conclusions.' if not history else
                           f"Latest assessment: {score}% across {history[-1]['count']} question(s). " + (' '.join(reasons) if score < 80 else 'Correct on most assessed concepts; schedule a short retention check.'),
                           confidence='No evidence' if not history else 'Limited evidence' if history[-1]['count'] < 3 else 'Multiple questions'))
    return result

def plan(s, topics):
    days, minutes = s['settings']['days'], s['settings']['minutes']
    ranked = sorted(topics, key=lambda t: ((100 - (t['score'] if t['score'] is not None else 40)) * (1 + min(t['exam_frequency'], 10) * .15)), reverse=True)
    slots = []
    if not ranked:
        return slots
    # At most 25-minute blocks. Daily total never exceeds the stated budget.
    for day in range(1, days + 1):
        remaining = minutes
        index = 0
        while remaining > 0:
            t = ranked[(index + (day - 1) * 2) % len(ranked)]
            duration = min(25, remaining)
            key = f"{len(s['attempts'])}-{days}-{minutes}-{day}-{index}-{t['id']}"
            slots.append({'id': key, 'day': day, 'minutes': duration, 'topic_id': t['id'], 'topic': t['name'],
                          'action': 'Retrieve and explain, then re-test' if t['score'] is not None and t['score'] >= 80 else 'Review source → recall without notes → re-test',
                          'reason': f"{t['level'].title()} · {t['exam_frequency']} mapped past-paper question(s)",
                          'done': key in s['completed'], 'sources': t['sources'][:1]})
            remaining -= duration
            index += 1
    return slots

