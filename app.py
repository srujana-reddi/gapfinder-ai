def mappings(s):
    mapped = []
    pseudo = [{'id': t['id'], 'text': t['name']} for t in s['topics']]
    for c in s['chunks']:
        if c['kind'] != 'paper':
            continue
        for line in c['text'].splitlines():
            if len(line.split()) < 4:
                continue
            matches = rag.retrieve(line, pseudo, 2)
            match = matches[0] if matches else None
            mapped.append({'question': line, 'topic_id': match['id'] if match else None,
                           'confidence': 'review' if len(matches) > 1 and matches[1]['relevance'] > matches[0]['relevance'] * .8 else 'matched' if match else 'unmapped',
                           'source': c})
    return mapped

def broad_topics(text):
    candidates = []
    in_answer = False
    for line in text.splitlines():
        line = line.strip()
        if re.match(r'^(?:\d+[.)]\s*)?(?:answer|ans|a)\s*[:.)-]', line, re.I):
            in_answer = True
            continue
        if '?' in line or re.match(r'^Q(?:uestion)?\s*\d+\b', line, re.I):
            in_answer = False
            continue
        heading = re.match(r'^(?:#+\s+|(?:unit|module|chapter|section|part)\s+\d+\b)', line, re.I)
        if in_answer and not heading:
            continue
        if heading:
            in_answer = False
        for part in re.split(r'\s{2,}|\s*[|•]\s*', line.strip()):
            title = re.sub(r'^(?:#+\s*|[-*]\s+|\d+[.)]\s+)', '', part).strip().rstrip(':')
            if not 2 <= len(title) <= 72 or not 1 <= len(title.split()) <= 7:
                continue
            if re.search(r'[?!.,;]$|^(?:page\s*\d*|syllabus|course outline|topics|contents|aiml interview|questions?\s*&\s*answers?)$|\binterview questions\b|^(?:q\d+|answer|example|what|why|how|explain|describe|compare|define)\b', title, re.I):
                continue
            if re.search(r'\b(?:is|are|was|were|can|should|because)\b', title, re.I):
                continue
            if not title[0].isupper() and not heading:
                continue
            candidates.append(title)
    sections = [t for t in candidates if re.match(r'^(unit|module|chapter)\s+\d+\b', t, re.I)]
    unique = {}
    for title in sections if len(sections) > 1 else candidates:
        unique.setdefault(title.casefold(), title)
    return list(unique.values())[:24]

