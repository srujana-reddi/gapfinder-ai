def add_document(s, name, kind, pages):
    if kind not in ('syllabus', 'notes', 'paper'):
        raise ValueError('Choose syllabus, notes, or past paper.')
    doc_id = uid()
    chunks = []
    for page, text in pages:
        section = 'Opening section'
        # Preserve paragraphs and section headings, then bound each retrieval unit.
        for paragraph in re.split(r'\n\s*\n', text):
            lines = paragraph.strip().splitlines()
            if not lines:
                continue
            if len(lines[0]) < 100:
                section = lines[0].strip('# ').strip()
            for start in range(0, len(paragraph), 1000):
                piece = paragraph[max(0, start - 120):start + 1000].strip()
                if piece:
                    chunks.append({'id': uid(), 'document_id': doc_id, 'name': name, 'kind': kind,
                                   'page': page, 'section': section, 'text': piece})
    if not chunks:
        raise ValueError('No readable text found. Scanned PDFs need OCR first; upload a text-based PDF or TXT file.')
    s['documents'].append({'id': doc_id, 'name': name, 'kind': kind, 'pages': len(pages), 'chunks': len(chunks), 'created': now()})
    s['chunks'].extend(chunks)
    if kind == 'syllabus':
        for title in broad_topics('\n'.join(text for _, text in pages)):
            if not any(t['name'].casefold() == title.casefold() for t in s['topics']):
                s['topics'].append({'id': uid(), 'name': title, 'parent': '', 'document_id': doc_id})
    return doc_id

@app.post('/api/upload')
@authenticated
def upload():
    f = request.files.get('file')
    if not f or not f.filename:
        raise ValueError('Select a PDF or text file.')
    raw = f.read(UPLOAD_LIMIT + 1)
    if len(raw) > UPLOAD_LIMIT:
        return jsonify(error='You can only upload files up to 100 KB.'), 413
    name = Path(f.filename.replace('\\', '/')).name[:150]
    kind = request.form.get('kind')
    if name.lower().endswith('.pdf'):
        try:
            reader = PdfReader(io.BytesIO(raw))
            if len(reader.pages) > 300:
                raise ValueError('Use a PDF with 300 pages or fewer.')
            pages = [(i + 1, p.extract_text() or '') for i, p in enumerate(reader.pages)]
        except ValueError:
            raise
        except Exception:
            raise ValueError('This PDF could not be read. Try an unlocked, text-based PDF.')
    elif name.lower().endswith(('.txt', '.md')):
        try:
            pages = [(1, raw.decode('utf-8-sig'))]
        except UnicodeDecodeError:
            raise ValueError('Text files must use UTF-8 encoding.')
    else:
        raise ValueError('Supported formats: PDF, TXT, MD.')
    if sum(len(p[1]) for p in pages) > 800000:
        raise ValueError('Extracted text is too long. Split this material into smaller files.')
    s = state()
    if len(s['documents']) >= 40:
        raise ValueError('Maximum 40 materials per account. Remove an unused material first.')
    add_document(s, name, kind, pages)
    save(s)
    return jsonify(ok=True)

