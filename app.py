    # Windows can allow duplicate development servers to bind the same port.
    # Keep a process-lifetime lock so launching twice never serves stale builds.
    server_lock = open(INSTANCE / 'server.lock', 'a+b')
    server_lock.seek(0)
    if not server_lock.read(1):
        server_lock.write(b'1')
        server_lock.flush()
    server_lock.seek(0)
    try:
        if os.name == 'nt':
            import msvcrt
            msvcrt.locking(server_lock.fileno(), msvcrt.LK_NBLCK, 1)
        else:
            import fcntl
            fcntl.flock(server_lock.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        print(f"GapFinder is already running. Open http://127.0.0.1:{os.getenv('PORT', '8765')} instead of starting another server.")
        sys.exit(1)
    app.run(host='127.0.0.1', port=int(os.getenv('PORT', '8765')), debug=False)
